-- A3 sin la contraseña de la base (docs/guia-consolas.md, bloque 2): lo mismo que datos/a3.sh, pero
-- desde el editor SQL del panel de Supabase de Persevera. Pega este fichero entero y pulsa «Run».
-- Solo lee: es una sola SELECT sobre el catálogo, sin ninguna fila de las tablas.
-- Devuelve una fila con una columna, «esquema»: la estructura de las 21 tablas y las 2 vistas de A3
-- (columnas, restricciones, índices, RLS, políticas, disparadores y permisos), el texto de las
-- funciones de las que dependen (también las que llaman por dentro), los enum y la lista de
-- dependencias. Los nombres de tipos y funciones dentro de las expresiones salen sin «public.».
with recursive
objetivo(rel, nombre, relkind) as (
  select c.oid, c.relname, c.relkind from pg_class c
   where c.relnamespace = 'public'::regnamespace and c.relname = any (array[
     'oposiciones','bloques','temas','epigrafes','tema_epigrafe','preguntas',
     'minicasos','minicaso_preguntas','supuestos_originales','supuesto_original_preguntas',
     'supuestos_oficiales','supuesto_oficial_preguntas','marcado_items','marcado_unidades','psico_items_graficos',
     'usuario_oposicion','respuestas_usuario','pregunta_respondida','study_activity_log','simulacros','simulacro_sesiones',
     'v_casos_para_revisar','v_estado_pregunta_usuario'])
),
-- Las funciones de public que no son de una extensión: son las únicas cuyo cuerpo se lee.
propias(oid, proname, prosrc) as (
  select p.oid, p.proname, p.prosrc from pg_proc p
   where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend e
                      where e.classid = 'pg_proc'::regclass and e.objid = p.oid and e.deptype = 'e')
),
usos(rel, por, fn, tipo) as (
  select t.tgrelid, 'disparador ' || t.tgname, t.tgfoid, null::oid
    from pg_trigger t where not t.tgisinternal and t.tgrelid in (select rel from objetivo)
  union all
  select coalesce(pol.polrelid, ad.adrelid, con.conrelid, rw.ev_class),
         case d.classid when 'pg_policy'::regclass then 'política ' || pol.polname
                        when 'pg_attrdef'::regclass then 'valor por defecto'
                        when 'pg_constraint'::regclass then 'restricción ' || con.conname
                        else 'vista' end,
         case when d.refclassid = 'pg_proc'::regclass then d.refobjid end,
         case when d.refclassid = 'pg_type'::regclass then d.refobjid end
    from pg_depend d
    left join pg_policy pol on d.classid = 'pg_policy'::regclass and pol.oid = d.objid
    left join pg_attrdef ad on d.classid = 'pg_attrdef'::regclass and ad.oid = d.objid
    left join pg_constraint con on d.classid = 'pg_constraint'::regclass and con.oid = d.objid
    left join pg_rewrite rw on d.classid = 'pg_rewrite'::regclass and rw.oid = d.objid
   where d.refclassid in ('pg_proc'::regclass, 'pg_type'::regclass)
     and coalesce(pol.polrelid, ad.adrelid, con.conrelid, rw.ev_class) in (select rel from objetivo)
  union all
  select a.attrelid, 'columna ' || a.attname, null, a.atttypid
    from pg_attribute a
   where a.attrelid in (select rel from objetivo) and a.attnum > 0 and not a.attisdropped
),
base(fn) as (
  select fn from usos where fn is not null
  union
  select oid from propias where proname = any (array['preguntas_aleatorias'])  -- pedidas por nombre
),
-- Y las que llaman por dentro: su nombre seguido de «(» en el cuerpo de una que ya está.
cierre(fn) as (
  select fn from base
  union
  select q.oid from cierre c join propias p on p.oid = c.fn
    join propias q on p.prosrc ~ ('\m' || q.proname || '\s*\(')
),
columnas(rel, def) as (
  select o.rel, string_agg(format('    %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
           case when a.attcollation <> 0 and a.attcollation <> ty.typcollation
                then (select format(' COLLATE %I.%I', cn.nspname, co.collname)
                        from pg_collation co join pg_namespace cn on cn.oid = co.collnamespace
                       where co.oid = a.attcollation)
                else '' end,
           case when a.attgenerated = 's' then format(' GENERATED ALWAYS AS (%s) STORED', pg_get_expr(ad.adbin, ad.adrelid))
                when ad.adbin is not null then ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
                when a.attidentity = 'a' then ' GENERATED ALWAYS AS IDENTITY'
                when a.attidentity = 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
                else '' end,
           case when a.attnotnull then ' NOT NULL' else '' end),
         E',\n' order by a.attnum)
    from objetivo o
    join pg_attribute a on a.attrelid = o.rel and a.attnum > 0 and not a.attisdropped
    join pg_type ty on ty.oid = a.atttypid
    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
   where o.relkind in ('r', 'p')
   group by o.rel
),
piezas(orden, clave, texto) as (
  -- 1. Los enum propios que usan las columnas.
  select 1, t.typname::text, format('CREATE TYPE %I.%I AS ENUM (%s);', n.nspname, t.typname,
              string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
    from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
   where n.nspname = 'public' and t.oid in (select tipo from usos where tipo is not null)
   group by n.nspname, t.typname
  union all
  -- 1b. Las secuencias de las columnas serial (las de identidad van con su columna).
  select 1, 'secuencia ' || s.relname,
         format('CREATE SEQUENCE public.%I AS %s START WITH %s INCREMENT BY %s;', s.relname,
                format_type(sq.seqtypid, null), sq.seqstart, sq.seqincrement)
    from objetivo o
    join pg_depend d on d.refclassid = 'pg_class'::regclass and d.refobjid = o.rel
                    and d.classid = 'pg_class'::regclass and d.deptype = 'a'
    join pg_class s on s.oid = d.objid and s.relkind = 'S'
    join pg_sequence sq on sq.seqrelid = s.oid
  union all
  -- 3. Las tablas, con sus columnas (después de las funciones, que usan sus valores por defecto).
  select 3, o.nombre::text, format(E'CREATE TABLE public.%I (\n%s\n);', o.nombre, c.def)
    from objetivo o join columnas c on c.rel = o.rel
  union all
  -- 2. Las funciones (las de extensiones, solo nombradas). Van antes que las tablas.
  select 2, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         case when exists (select 1 from pg_depend e
                            where e.classid = 'pg_proc'::regclass and e.objid = p.oid and e.deptype = 'e')
              then format('-- FUNCTION public.%I(%s) es de la extensión %s: no se copia, se instala la extensión.',
                          p.proname, pg_get_function_identity_arguments(p.oid),
                          (select x.extname from pg_depend e join pg_extension x on x.oid = e.refobjid
                            where e.classid = 'pg_proc'::regclass and e.objid = p.oid and e.deptype = 'e' limit 1))
              else format(E'-- public.%I(%s) (%s, de %s)\n-- permisos: %s\n%s;',
                          p.proname, pg_get_function_identity_arguments(p.oid),
                          case when p.prosecdef then 'SECURITY DEFINER' else 'SECURITY INVOKER' end,
                          pg_get_userbyid(p.proowner),
                          coalesce(p.proacl::text, 'los de serie (EXECUTE para PUBLIC)'),
                          pg_get_functiondef(p.oid))
         end
    from cierre join pg_proc p on p.oid = cierre.fn
   where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
  union all
  -- 4. Las vistas.
  select 4, o.nombre::text,
         format(E'CREATE VIEW public.%I%s AS\n%s', o.nombre,
                case when c.reloptions is not null
                     then ' WITH (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
                pg_get_viewdef(o.rel, true))
    from objetivo o join pg_class c on c.oid = o.rel
   where o.relkind in ('v', 'm')
  union all
  -- 4b. A qué columna pertenece cada secuencia serial.
  select 4, 'secuencia ' || s.relname,
         format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', s.relname, o.nombre, a.attname)
    from objetivo o
    join pg_depend d on d.refclassid = 'pg_class'::regclass and d.refobjid = o.rel
                    and d.classid = 'pg_class'::regclass and d.deptype = 'a'
    join pg_class s on s.oid = d.objid and s.relkind = 'S'
    join pg_attribute a on a.attrelid = o.rel and a.attnum = d.refobjsubid
  union all
  -- 5. Restricciones: primero claves, únicas y checks; las claves ajenas, después.
  select case when con.contype = 'f' then 6 else 5 end, o.nombre || ' ' || con.conname,
         format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', o.nombre, con.conname, pg_get_constraintdef(con.oid))
    from objetivo o join pg_constraint con on con.conrelid = o.rel
   where con.contype in ('p', 'u', 'c', 'x', 'f')
  union all
  -- 7. Los índices que no son de una restricción.
  select 7, o.nombre || ' ' || ic.relname, pg_get_indexdef(i.indexrelid) || ';'
    from objetivo o join pg_index i on i.indrelid = o.rel join pg_class ic on ic.oid = i.indexrelid
   where not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid and con.conrelid = o.rel)
  union all
  -- 8. RLS.
  select 8, o.nombre::text,
         format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', o.nombre)
         || case when c.relforcerowsecurity then format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', o.nombre) else '' end
    from objetivo o join pg_class c on c.oid = o.rel
   where c.relrowsecurity
  union all
  -- 9. Las políticas.
  select 9, o.nombre || ' ' || pol.polname,
         format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;', pol.polname, o.nombre,
                case when pol.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
                case pol.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE'
                                when 'd' then 'DELETE' else 'ALL' end,
                case when pol.polroles = '{0}' then 'public'
                     else (select string_agg(quote_ident(r.rolname), ', ' order by r.rolname)
                             from pg_roles r where r.oid = any (pol.polroles)) end,
                case when pol.polqual is not null then E'\n  USING (' || pg_get_expr(pol.polqual, pol.polrelid) || ')' else '' end,
                case when pol.polwithcheck is not null then E'\n  WITH CHECK (' || pg_get_expr(pol.polwithcheck, pol.polrelid) || ')' else '' end)
    from objetivo o join pg_policy pol on pol.polrelid = o.rel
  union all
  -- 10. Los disparadores.
  select 10, o.nombre || ' ' || t.tgname, pg_get_triggerdef(t.oid) || ';'
    from objetivo o join pg_trigger t on t.tgrelid = o.rel
   where not t.tgisinternal
  union all
  -- 11. Los permisos de cada tabla y vista (sin los de su dueño).
  select 11, o.nombre || ' ' || coalesce(r.rolname, 'PUBLIC'),
         format('GRANT %s ON TABLE public.%I TO %s;',
                string_agg(x.privilege_type, ', ' order by x.privilege_type), o.nombre,
                case when x.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end)
    from objetivo o join pg_class c on c.oid = o.rel
    cross join lateral aclexplode(c.relacl) x
    left join pg_roles r on r.oid = x.grantee
   where x.grantee <> c.relowner
   group by o.nombre, x.grantee, r.rolname
  union all
  select 11, o.nombre || ' ' || coalesce(r.rolname, 'PUBLIC') || ' ' || a.attname,
         format('GRANT %s (%I) ON TABLE public.%I TO %s;',
                string_agg(x.privilege_type, ', ' order by x.privilege_type), a.attname, o.nombre,
                case when x.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end)
    from objetivo o join pg_attribute a on a.attrelid = o.rel and a.attnum > 0 and a.attacl is not null
    cross join lateral aclexplode(a.attacl) x
    left join pg_roles r on r.oid = x.grantee
   group by o.nombre, a.attname, x.grantee, r.rolname
  union all
  -- 12. De qué depende cada tabla (lo que en datos/a3.sh sale en esquema-persevera-dependencias.txt).
  select 12, d.tabla || ' ' || d.por || ' ' || coalesce(d.funcion, '') || coalesce(d.tipo, ''),
         format('-- dependencia: %s | %s | %s | %s', d.tabla, d.por, coalesce(d.funcion, ''), coalesce(d.tipo, ''))
    from (select distinct format('public.%I', c.relname) as tabla, u.por,
                 case when p.oid is not null
                      then format('%I.%I(%s)', pn.nspname, p.proname, pg_get_function_identity_arguments(p.oid)) end as funcion,
                 case when ty.oid is not null then format('%I.%I', tn.nspname, ty.typname) end as tipo
            from usos u
            join pg_class c on c.oid = u.rel
            left join pg_proc p on p.oid = u.fn
            left join pg_namespace pn on pn.oid = p.pronamespace
            left join pg_type ty on ty.oid = u.tipo
            left join pg_namespace tn on tn.oid = ty.typnamespace
           where (p.oid is not null and pn.nspname not in ('pg_catalog', 'information_schema'))
              or (ty.oid is not null and tn.nspname not in ('pg_catalog', 'information_schema') and ty.typrelid = 0)) d
)
select format(E'-- Sacado de Persevera, producción (rljfcmjvulmjooxoxzxo), el %s, desde el editor SQL del panel\n'
              '-- con datos/a3-editor.sql: solo el catálogo, sin ninguna fila. Postgres %s.\n'
              '-- Tablas y vistas de A3 encontradas: %s de 23.\n'
              'set check_function_bodies = off;\n\n',
              to_char(now() at time zone 'Europe/Madrid', 'DD-MM-YYYY HH24:MI') || ' (hora de Madrid)',
              current_setting('server_version'),
              (select count(*) from objetivo))
       || string_agg(texto, E'\n\n' order by orden, clave)
       || E'\n\n-- FIN del esquema de A3.\n' as esquema
  from piezas;
